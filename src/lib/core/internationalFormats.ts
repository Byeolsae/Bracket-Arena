export function getInternationalFormatProfile(id: string) {
  return INTERNATIONAL_FORMAT_PROFILES.find((profile) => profile.id === id);
}

export function getInternationalFormatGroups() {
  return INTERNATIONAL_FORMAT_PROFILES.reduce<Record<string, InternationalFormatProfile[]>>((groups, profile) => {
    const key = `${profile.game} (${profile.gameCode})`;
    groups[key] = [...(groups[key] ?? []), profile];
    return groups;
  }, {});
}
