export function getTeamCountRule(profileId: string): TeamCountRule | undefined {
  return TEAM_COUNT_RULES[profileId];
}

export function isTeamCountAllowed(profileId: string, count: number): boolean {
  const rule = getTeamCountRule(profileId);
  if (!rule) return true;
  if (rule.exact) return rule.exact.includes(count);
  if (rule.min !== undefined && count < rule.min) return false;
  if (rule.max !== undefined && count > rule.max) return false;
  return true;
}

